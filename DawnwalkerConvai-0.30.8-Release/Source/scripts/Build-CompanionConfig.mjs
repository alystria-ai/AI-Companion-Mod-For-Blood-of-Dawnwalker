import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const roster=JSON.parse(readFileSync(root+'characters/companion-roster.json','utf8'));
const assets=readFileSync(root+'runtime/companion-asset-catalog.tsv','utf8').trim().split(/\r?\n/).slice(1).map(line=>line.split('\t'));
// Combat abilities belong to each definition's native action trees. This
// catalogue selects character definitions; it does not grant or gate powers.
// Summoned_CoenHelper_Ambrus resolves to BP_Ambrus_Clone and retired during
// testing. Use the regular character body/AI, with per-instance allegiance.
const regular={bakir:'NPCDef_Bakir_Base',ambrus:'NPCDef_Ambrus_Base',xanthe:'NPCDef_Xanthe_Base'};
function characterPath(c){
 const asset=regular[c.id];if(!asset)return c.candidates[0].generatedClassPathCandidate;
 const row=assets.find(r=>r[1]===asset);if(!row)throw Error('Missing regular companion '+asset);
 return row[0]+'.'+asset+'_C';
}
const q=JSON.stringify;
// Keep researched/world-dialogue profiles even when removed from the summon menu.
const excludedCompanions=new Set(['pieter','vladimir']);
const named=roster.characters.filter(c=>!excludedCompanions.has(c.id)).map(c=>({id:c.id,name:c.name,path:characterPath(c)}));
const selected=[...named.map(c=>({...c,category:'story',chat:true})),...JSON.parse(readFileSync(root+'characters/combat-roster.json','utf8'))];
writeFileSync(root+'characters/companion-config.json',JSON.stringify({version:1,limit:0,damageMultiplier:2.5,characters:selected},null,2)+'\n');
writeFileSync(root+'mod/Scripts/companion_config.lua','-- Generated by scripts/Build-CompanionConfig.mjs from the captured asset catalogue.\nreturn {limit=0,damageMultiplier=2.5,characters={\n'+selected.map(c=>` {id=${q(c.id)},name=${q(c.name)},path=${q(c.path)},category=${q(c.category)},chat=${c.chat},archetype=${q(c.archetype||c.id)}}`).join(',\n')+'\n}}\n');
console.log('Generated '+selected.length+' companion candidates.');
